import asyncio
import sys
from logging.config import fileConfig
from pathlib import Path

from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from alembic import context

# 添加项目根目录到 Python 路径
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

# 导入所有模型，确保 Base.metadata 包含所有表
from app.models.base import Base  # noqa: E402
import app.models  # noqa: E402, F401 — 触发所有模型注册

# 从 .env 动态获取数据库 URL，替代 alembic.ini 中硬编码的明文密码
from app.config import settings  # noqa: E402
from sqlalchemy import URL  # noqa: E402

_db_url = URL.create(
    drivername="mysql+aiomysql",
    username=settings.DB_USER,
    password=settings.DB_PASSWORD,
    host=settings.DB_HOST,
    port=settings.DB_PORT,
    database=settings.DB_NAME,
    query={"charset": "utf8mb4"},
)

# this is the Alembic Config object
config = context.config

# 动态注入数据库 URL，覆盖 alembic.ini 中的占位值
config.set_main_option("sqlalchemy.url", _db_url.render_as_string(hide_password=False))

# Interpret the config file for Python logging.
# This line sets up loggers basically.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# add your model's MetaData object here
# for 'autogenerate' support
target_metadata = Base.metadata

# other values from the config, defined by the needs of env.py,
# can be acquired:
